type FrRepr = <Fr as PrimeField>::Repr;

/// Modulus of the BN254 scalar field, over which Baby JubJub is defined.
const FIELD_MODULUS_DEC: &str =
    "21888242871839275222246405745257275088548364400416034343698204186575808495617";

/// Order `l` of the prime-order subgroup generated by B8.
const SUBGROUP_ORDER_DEC: &str =
    "2736030358979909402780800718157159386076813972158567259200215660948447373041";

/// Cofactor `h`: the full curve group has order `h * l`.
const COFACTOR: u32 = 8;

/// Twisted Edwards parameters: a*x^2 + y^2 = 1 + d*x^2*y^2.
const CURVE_A: u64 = 168700;
const CURVE_D: u64 = 168696;

/// B8, the generator of the prime-order subgroup (same base point as circomlib / babyjubjub-rs).
const B8_X_DEC: &str =
    "5299619240641551281634865583518297030282874472190772894086521144482721001553";
const B8_Y_DEC: &str =
    "16950150798460657717958625567821834550301663161624707787222815936182638968203";

/// Domain separation tag for `hash_to_point`. Changing it changes every output.
const HASH_TO_POINT_DST: &[u8] = b"babyjubjub-py/v1/hash_to_point/SHA-256/try-and-increment";

/// Upper bound on try-and-increment attempts. Each attempt succeeds with probability
/// roughly 0.38, so running out has probability below 2^-170.
const HASH_TO_POINT_MAX_ATTEMPTS: u32 = 256;

struct Constants {
    a: Fr,
    d: Fr,
    /// (p - 1) / 2: field elements above this are "negative" for point compression.
    half_p: FrRepr,
    field_modulus: BigInt,
    subgroup_order: BigInt,
    curve_order: BigInt,
    generator: Point,
}

fn constants() -> &'static Constants {
    static CONSTANTS: OnceLock<Constants> = OnceLock::new();
    CONSTANTS.get_or_init(|| {
        let mut half_p = Fr::char();
        half_p.div2();
        let field_modulus = BigInt::from_str_radix(FIELD_MODULUS_DEC, 10).expect("valid constant");
        let subgroup_order =
            BigInt::from_str_radix(SUBGROUP_ORDER_DEC, 10).expect("valid constant");
        let curve_order = &subgroup_order * COFACTOR;
        Constants {
            a: fr_from_u64(CURVE_A),
            d: fr_from_u64(CURVE_D),
            half_p,
            field_modulus,
            subgroup_order,
            curve_order,
            generator: Point {
                x: Fr::from_str(B8_X_DEC).expect("valid constant"),
                y: Fr::from_str(B8_Y_DEC).expect("valid constant"),
            },
        }
    })
}

/// Baby JubJub elliptic curve point (twisted Edwards form, affine coordinates).
///
/// Points built through the public constructors (`ECPoint(x, y)`, `from_bytes`,
/// `from_bytes_uncompressed`) are checked to lie on the curve and in the prime-order
/// subgroup generated by B8. `from_bytes_uncompressed_unchecked` skips both checks.
#[pyclass(frozen, module = "babyjubjub_py")]
#[derive(Clone)]
struct ECPoint {
    point: Point,
}

#[pymethods]
impl ECPoint {
    /// Create a point from hex coordinates, checking that it is on the curve and in the
    /// prime-order subgroup. Raises ValueError otherwise.
    #[new]
    fn new(py: Python<'_>, x_hex: &str, y_hex: &str) -> PyResult<Self> {
        let point = Point {
            x: parse_hex_coordinate(x_hex)?,
            y: parse_hex_coordinate(y_hex)?,
        };
        validate(py, &point)?;
        Ok(ECPoint { point })
    }

    /// The generator B8 of the prime-order subgroup.
    #[staticmethod]
    fn generator() -> Self {
        ECPoint {
            point: constants().generator.clone(),
        }
    }

    /// The identity point (0, 1).
    #[staticmethod]
    fn infinity() -> Self {
        ECPoint { point: identity() }
    }

    /// scalar * B8. The scalar (int, or decimal / 0x-hex string, optionally signed) is
    /// reduced modulo SUBGROUP_ORDER first, so negative scalars are handled correctly.
    #[staticmethod]
    fn from_scalar(py: Python<'_>, scalar: &Bound<'_, PyAny>) -> PyResult<Self> {
        let k = reduce(&extract_scalar(scalar)?, &constants().subgroup_order);
        let generator = &constants().generator;
        Ok(py.detach(|| ECPoint {
            point: generator.mul_scalar(&k),
        }))
    }

    /// Point addition.
    fn add(&self, other: &ECPoint) -> Self {
        ECPoint {
            point: add_points(&self.point, &other.point),
        }
    }

    /// Point negation.
    fn neg(&self) -> Self {
        ECPoint {
            point: negate(&self.point),
        }
    }

    /// Point subtraction.
    fn sub(&self, other: &ECPoint) -> Self {
        ECPoint {
            point: add_points(&self.point, &negate(&other.point)),
        }
    }

    /// scalar * self. The scalar (int, or decimal / 0x-hex string, optionally signed) is
    /// reduced modulo CURVE_ORDER (8 * l), which is correct for every point on the curve,
    /// including points created with `from_bytes_uncompressed_unchecked`.
    fn scalar_mult(&self, py: Python<'_>, scalar: &Bound<'_, PyAny>) -> PyResult<Self> {
        let k = extract_scalar(scalar)?;
        Ok(self.mul_bigint(py, &k))
    }

    /// True if this is the identity point.
    fn is_infinity(&self) -> bool {
        is_identity(&self.point)
    }

    /// True if the coordinates satisfy the curve equation.
    fn is_on_curve(&self) -> bool {
        is_on_curve(&self.point)
    }

    /// True if the point is on the curve and SUBGROUP_ORDER * self is the identity.
    fn is_in_subgroup(&self, py: Python<'_>) -> bool {
        is_on_curve(&self.point) && py.detach(|| is_in_subgroup(&self.point))
    }

    /// x coordinate as a 0x-prefixed, 64-digit hex string.
    fn x_hex(&self) -> String {
        fr_to_hex(&self.point.x)
    }

    /// y coordinate as a 0x-prefixed, 64-digit hex string.
    fn y_hex(&self) -> String {
        fr_to_hex(&self.point.y)
    }

    /// Compressed 32-byte encoding (little-endian y, sign of x in the top bit), compatible
    /// with circomlib and babyjubjub-rs.
    fn to_bytes<'py>(&self, py: Python<'py>) -> Bound<'py, PyBytes> {
        PyBytes::new(py, &compress(&self.point))
    }

    /// Uncompressed 64-byte encoding: little-endian x followed by little-endian y.
    fn to_bytes_uncompressed<'py>(&self, py: Python<'py>) -> Bound<'py, PyBytes> {
        PyBytes::new(py, &encode_uncompressed(&self.point))
    }

    /// Decode a compressed point, checking that it is canonical and in the prime-order
    /// subgroup. Raises ValueError otherwise.
    #[staticmethod]
    fn from_bytes(py: Python<'_>, data: &Bound<'_, PyAny>) -> PyResult<Self> {
        let bytes = extract_bytes(data)?;
        let arr: [u8; 32] = bytes.as_ref().try_into().map_err(|_| {
            PyValueError::new_err(format!(
                "Invalid byte length {}, expected 32 bytes",
                bytes.len()
            ))
        })?;
        let point = decompress(&arr).map_err(PyValueError::new_err)?;
        validate(py, &point)?;
        Ok(ECPoint { point })
    }

    /// Decode a 64-byte uncompressed point, checking that it is on the curve and in the
    /// prime-order subgroup. Raises ValueError otherwise.
    #[staticmethod]
    fn from_bytes_uncompressed(py: Python<'_>, data: &Bound<'_, PyAny>) -> PyResult<Self> {
        let point = decode_uncompressed(&extract_bytes(data)?)?;
        validate(py, &point)?;
        Ok(ECPoint { point })
    }

    /// Decode a 64-byte uncompressed point WITHOUT the on-curve and subgroup checks.
    ///
    /// Only the byte length and that each coordinate is below the field modulus are
    /// checked. Use this only for bytes produced by `to_bytes_uncompressed` on a point you
    /// already trust (e.g. passing points between your own worker processes).
    #[staticmethod]
    fn from_bytes_uncompressed_unchecked(data: &Bound<'_, PyAny>) -> PyResult<Self> {
        let point = decode_uncompressed(&extract_bytes(data)?)?;
        Ok(ECPoint { point })
    }

    /// Hash arbitrary bytes to a point of the prime-order subgroup whose discrete
    /// logarithm with respect to the generator is unknown.
    ///
    /// Try-and-increment: for counter = 0, 1, ... compute
    /// SHA-256(len(DST) || DST || data || counter_be32), read the low 254 bits
    /// (little-endian) as a candidate y and bit 255 as the sign of x, decompress, and
    /// multiply by the cofactor 8. The first candidate that is a valid, non-identity
    /// point is returned. Deterministic, but not constant-time and not RFC 9380.
    #[staticmethod]
    fn hash_to_point(py: Python<'_>, data: &[u8]) -> PyResult<Self> {
        py.detach(|| hash_to_curve(data))
            .map(|point| ECPoint { point })
            .ok_or_else(|| PyRuntimeError::new_err("hash_to_point: no point found"))
    }

    /// The pre-0.2.0 `hash_to_point`: (SHA-256(data) mod l) * B8.
    ///
    /// The discrete log of the output with respect to the generator is SHA-256(data), so
    /// it is public. Kept only to reproduce old outputs; do not use where an
    /// independent generator is required.
    #[staticmethod]
    fn hash_to_scalar_times_generator(py: Python<'_>, data: &[u8]) -> Self {
        let digest = Sha256::digest(data);
        let k = BigInt::from_bytes_be(Sign::Plus, &digest) % &constants().subgroup_order;
        let generator = &constants().generator;
        py.detach(|| ECPoint {
            point: generator.mul_scalar(&k),
        })
    }

    fn __add__(&self, other: &ECPoint) -> Self {
        self.add(other)
    }

    fn __sub__(&self, other: &ECPoint) -> Self {
        self.sub(other)
    }

    fn __neg__(&self) -> Self {
        self.neg()
    }

    /// point * int
    fn __mul__(&self, py: Python<'_>, scalar: BigInt) -> Self {
        self.mul_bigint(py, &scalar)
    }

    /// int * point
    fn __rmul__(&self, py: Python<'_>, scalar: BigInt) -> Self {
        self.mul_bigint(py, &scalar)
    }

    fn __eq__(&self, other: &ECPoint) -> bool {
        self.point.x == other.point.x && self.point.y == other.point.y
    }

    fn __hash__(&self) -> u64 {
        let mut hasher = DefaultHasher::new();
        self.point.x.into_repr().hash(&mut hasher);
        self.point.y.into_repr().hash(&mut hasher);
        hasher.finish()
    }

    /// Pickle support. Unpickling uses `from_bytes_uncompressed_unchecked`; pickle data
    /// must be trusted anyway, since unpickling can execute arbitrary code.
    fn __reduce__<'py>(
        &self,
        py: Python<'py>,
    ) -> PyResult<(Bound<'py, PyAny>, (Bound<'py, PyBytes>,))> {
        let constructor = py
            .get_type::<ECPoint>()
            .getattr("from_bytes_uncompressed_unchecked")?;
        Ok((constructor, (self.to_bytes_uncompressed(py),)))
    }

    fn __repr__(&self) -> String {
        format!(
            "ECPoint(x={}, y={})",
            fr_to_hex(&self.point.x),
            fr_to_hex(&self.point.y)
        )
    }

    fn __str__(&self) -> String {
        self.__repr__()
    }
}

impl ECPoint {
    fn mul_bigint(&self, py: Python<'_>, scalar: &BigInt) -> Self {
        let k = reduce(scalar, &constants().curve_order);
        let point = &self.point;
        py.detach(|| ECPoint {
            point: point.mul_scalar(&k),
        })
    }
}

// ---------------------------------------------------------------------------
// Field helpers
// ---------------------------------------------------------------------------

fn fr_from_u64(value: u64) -> Fr {
    Fr::from_repr(FrRepr::from(value)).expect("small integers are field elements")
}

/// Parse a 32-byte little-endian canonical field element (rejects values >= p).
fn fr_from_le_bytes(bytes: &[u8]) -> Option<Fr> {
    let mut repr = FrRepr::default();
    repr.read_le(bytes).ok()?;
    Fr::from_repr(repr).ok()
}

fn fr_write_le(value: &Fr, out: &mut Vec<u8>) {
    value
        .into_repr()
        .write_le(out)
        .expect("writing to a Vec cannot fail");
}

fn fr_to_hex(value: &Fr) -> String {
    format!("0x{}", ff_ce::to_hex(value))
}

/// True if `value` is in the upper half of the field, i.e. greater than (p - 1) / 2.
fn is_negative(value: &Fr) -> bool {
    value.into_repr() > constants().half_p
}

fn parse_hex_coordinate(s: &str) -> PyResult<Fr> {
    let digits = s
        .strip_prefix("0x")
        .or_else(|| s.strip_prefix("0X"))
        .unwrap_or(s);
    let value = BigUint::from_str_radix(digits, 16)
        .map_err(|e| PyValueError::new_err(format!("Invalid hex coordinate {s:?}: {e}")))?;
    let bytes = value.to_bytes_le();
    if bytes.len() > 32 {
        return Err(non_canonical_coordinate(s));
    }
    let mut buf = [0u8; 32];
    buf[..bytes.len()].copy_from_slice(&bytes);
    fr_from_le_bytes(&buf).ok_or_else(|| non_canonical_coordinate(s))
}

fn non_canonical_coordinate(s: &str) -> PyErr {
    PyValueError::new_err(format!(
        "Coordinate {s} is not a canonical field element (must be < FIELD_MODULUS)"
    ))
}

