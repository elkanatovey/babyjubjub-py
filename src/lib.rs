// Scalar helpers
// ---------------------------------------------------------------------------

/// Accept a Python int, or a str holding an optionally signed decimal or 0x-hex integer.
fn extract_scalar(obj: &Bound<'_, PyAny>) -> PyResult<BigInt> {
    if let Ok(s) = obj.cast::<PyString>() {
        return parse_scalar_str(&s.to_cow()?);
    }
    obj.extract::<BigInt>().map_err(|_| {
        let type_name = obj
            .get_type()
            .name()
            .map(|n| n.to_string())
            .unwrap_or_else(|_| "?".to_string());
        PyTypeError::new_err(format!("scalar must be int or str, not {type_name}"))
    })
}

fn parse_scalar_str(s: &str) -> PyResult<BigInt> {
    let (negative, unsigned) = match s.strip_prefix('-') {
        Some(rest) => (true, rest),
        None => (false, s.strip_prefix('+').unwrap_or(s)),
    };
    let magnitude = match unsigned
        .strip_prefix("0x")
        .or_else(|| unsigned.strip_prefix("0X"))
    {
        Some(hex_digits) => BigUint::from_str_radix(hex_digits, 16),
        None => BigUint::from_str_radix(unsigned, 10),
    }
    .map_err(|e| PyValueError::new_err(format!("Invalid scalar {s:?}: {e}")))?;
    let sign = if negative { Sign::Minus } else { Sign::Plus };
    Ok(BigInt::from_biguint(sign, magnitude))
}

/// Reduce `n` into [0, modulus).
fn reduce(n: &BigInt, modulus: &BigInt) -> BigInt {
    let r = n % modulus;
    if r.sign() == Sign::Minus {
        r + modulus
    } else {
        r
    }
}

// ---------------------------------------------------------------------------
// Curve helpers
// ---------------------------------------------------------------------------

fn identity() -> Point {
    Point {
        x: Fr::zero(),
        y: Fr::one(),
    }
}

fn is_identity(p: &Point) -> bool {
    p.x.is_zero() && p.y == Fr::one()
}

fn add_points(p: &Point, q: &Point) -> Point {
    p.projective().add(&q.projective()).affine()
}

fn negate(p: &Point) -> Point {
    let mut x = p.x;
    x.negate();
    Point { x, y: p.y }
}

/// a*x^2 + y^2 == 1 + d*x^2*y^2
fn is_on_curve(p: &Point) -> bool {
    let c = constants();
    let mut x2 = p.x;
    x2.square();
    let mut y2 = p.y;
    y2.square();

    let mut lhs = c.a;
    lhs.mul_assign(&x2);
    lhs.add_assign(&y2);

    let mut rhs = c.d;
    rhs.mul_assign(&x2);
    rhs.mul_assign(&y2);
    rhs.add_assign(&Fr::one());

    lhs == rhs
}

/// l * P == identity. Only meaningful for points on the curve.
fn is_in_subgroup(p: &Point) -> bool {
    is_identity(&p.mul_scalar(&constants().subgroup_order))
}

fn validate(py: Python<'_>, p: &Point) -> PyResult<()> {
    if !is_on_curve(p) {
        return Err(PyValueError::new_err(
            "Point is not on the Baby JubJub curve",
        ));
    }
    if !py.detach(|| is_in_subgroup(p)) {
        return Err(PyValueError::new_err(
            "Point is on the curve but not in the prime-order subgroup",
        ));
    }
    Ok(())
}

fn compress(p: &Point) -> [u8; 32] {
    let mut out = Vec::with_capacity(32);
    fr_write_le(&p.y, &mut out);
    let mut arr: [u8; 32] = out.try_into().expect("field elements encode to 32 bytes");
    if is_negative(&p.x) {
        arr[31] |= 0x80;
    }
    arr
}

/// Recover x from y and the sign bit by solving x^2 = (1 - y^2) / (a - d*y^2).
fn recover_x(y: &Fr, negative: bool) -> Result<Fr, &'static str> {
    const NOT_ON_CURVE: &str = "No curve point has this y coordinate";
    let c = constants();
    let mut y2 = *y;
    y2.square();

    let mut numerator = Fr::one();
    numerator.sub_assign(&y2);

    let mut dy2 = c.d;
    dy2.mul_assign(&y2);
    let mut denominator = c.a;
    denominator.sub_assign(&dy2);

    let mut x2 = numerator;
    x2.mul_assign(&denominator.inverse().ok_or(NOT_ON_CURVE)?);

    if x2.is_zero() {
        return if negative {
            Err("Non-canonical encoding: sign bit set but x = 0")
        } else {
            Ok(Fr::zero())
        };
    }

    let mut x = x2.sqrt().ok_or(NOT_ON_CURVE)?;
    let mut check = x;
    check.square();
    if check != x2 {
        return Err(NOT_ON_CURVE);
    }
    if is_negative(&x) != negative {
        x.negate();
    }
    Ok(x)
}

fn decompress(bytes: &[u8; 32]) -> Result<Point, &'static str> {
    let mut y_bytes = *bytes;
    let negative = y_bytes[31] & 0x80 != 0;
    y_bytes[31] &= 0x7f;
    let y = fr_from_le_bytes(&y_bytes).ok_or("y coordinate is not below the field modulus")?;
    let x = recover_x(&y, negative)?;
    Ok(Point { x, y })
}

fn encode_uncompressed(p: &Point) -> Vec<u8> {
    let mut out = Vec::with_capacity(64);
    fr_write_le(&p.x, &mut out);
    fr_write_le(&p.y, &mut out);
    out
}

fn decode_uncompressed(bytes: &[u8]) -> PyResult<Point> {
    if bytes.len() != 64 {
        return Err(PyValueError::new_err(format!(
            "Invalid byte length {}, expected 64 bytes",
            bytes.len()
        )));
    }
    let x = fr_from_le_bytes(&bytes[..32])
        .ok_or_else(|| PyValueError::new_err("Invalid x coordinate"))?;
    let y = fr_from_le_bytes(&bytes[32..])
        .ok_or_else(|| PyValueError::new_err("Invalid y coordinate"))?;
    Ok(Point { x, y })
}

fn hash_to_curve(data: &[u8]) -> Option<Point> {
    let mut prefix = Sha256::new();
    prefix.update([HASH_TO_POINT_DST.len() as u8]);
    prefix.update(HASH_TO_POINT_DST);
    prefix.update(data);

    for counter in 0..HASH_TO_POINT_MAX_ATTEMPTS {
        let digest = prefix
            .clone()
            .chain_update(counter.to_be_bytes())
            .finalize();
        let mut y_bytes = [0u8; 32];
        y_bytes.copy_from_slice(&digest);
        let negative = y_bytes[31] & 0x80 != 0;
        y_bytes[31] &= 0x3f;

        let Some(y) = fr_from_le_bytes(&y_bytes) else {
            continue;
        };
        let Ok(x) = recover_x(&y, negative) else {
            continue;
        };

        // Clear the cofactor: 8 * P lies in the prime-order subgroup.
        let mut q = Point { x, y }.projective();
        for _ in 0..3 {
            q = q.add(&q);
        }
        let point = q.affine();
        if !is_identity(&point) {
            return Some(point);
        }
    }
    None
}

/// Borrow the contents of a `bytes` object, or copy any other sequence of ints in 0..256.
fn extract_bytes<'a>(obj: &'a Bound<'_, PyAny>) -> PyResult<Cow<'a, [u8]>> {
    if let Ok(b) = obj.cast::<PyBytes>() {
        return Ok(Cow::Borrowed(b.as_bytes()));
    }
    Ok(Cow::Owned(obj.extract::<Vec<u8>>()?))
}

/// Module constants and utilities
#[pymodule]
fn babyjubjub_py(m: &Bound<'_, PyModule>) -> PyResult<()> {
    m.add_class::<ECPoint>()?;

    let c = constants();
    m.add("__version__", env!("CARGO_PKG_VERSION"))?;
    m.add("CURVE_NAME", "Baby JubJub")?;
    // Modulus p of the base field (the BN254 scalar field).
    m.add("FIELD_MODULUS", c.field_modulus.clone())?;
    // Prime order l of the subgroup generated by ECPoint.generator() (B8).
    m.add("SUBGROUP_ORDER", c.subgroup_order.clone())?;
    // Order of the full curve group: COFACTOR * SUBGROUP_ORDER.
    m.add("CURVE_ORDER", c.curve_order.clone())?;
    m.add("COFACTOR", COFACTOR)?;

    Ok(())
}
